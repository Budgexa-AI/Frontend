export function defaultCurrencyForCountry(countryCode: string): string {
  const formattedCode = countryCode?.toUpperCase() ?? "";
  return COUNTRY_CURRENCY_MAP[formattedCode] ?? "NGN";
}

export function formatAmount(amount: number, code: string, currencies: CurrencyDefinition[]): string {
  const def = currencies.find((c) => c.code === code) ?? { symbol: code, decimals: 2 };
  const number = new Intl.NumberFormat("en-US", {
    style: "decimal", // ← formatting only, no currency/symbol resolution involved
    minimumFractionDigits: def.decimals,
    maximumFractionDigits: def.decimals,
  }).format(amount);
  return `${def.symbol}${number}`;
}
export function isSupportedCurrency(code: string): boolean {
  return code in SUPPORTED_CURRENCIES;
}

export function getCurrencyDefinition(code: string): CurrencyDefinition {
  return SUPPORTED_CURRENCIES[code?.toUpperCase()] ?? SUPPORTED_CURRENCIES.NGN;
}

export function formatCurrency(amount: number, currencyCode: string, locale = "en-US"): string {
  const def = getCurrencyDefinition(currencyCode);
  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency: def.code,
    minimumFractionDigits: def.decimals,
    maximumFractionDigits: def.decimals,
  }).format(amount);
}

